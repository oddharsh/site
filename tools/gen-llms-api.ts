// gen-llms-api.ts: the JSON endpoint list in public/llms.txt, from the code.

import { readFileSync, writeFileSync } from "node:fs";
import { OPERATIONS, exampleUrl } from "../src/worker/lib/public-api.ts";

export const LLMS_PATH = "public/llms.txt";
export const BEGIN = "<!-- endpoints: generated by tools/gen-llms-api.ts from src/worker/lib/public-api.ts; edit the operations there -->";
export const END = "<!-- /endpoints -->";
const ORIGIN = "https://aadhar.sh";
const WIDTH = 78;

function wrap(text: string, first: string, rest: string): string {
  const lines: string[] = [];
  let line = first;
  for (const word of text.split(/\s+/).filter(Boolean)) {
    const lead = line === first || line === rest;
    if (!lead && line.length + 1 + word.length > WIDTH) {
      lines.push(line);
      line = rest + word;
    } else {
      line += (lead ? "" : " ") + word;
    }
  }
  lines.push(line);
  return lines.join("\n");
}

export function endpointBlock(): string {
  const items = OPERATIONS.map((op) => {
    const label = `${op.method === "post" ? "POST " : ""}${op.path}`;
    const href = op.method === "get" ? `${ORIGIN}${exampleUrl(op)}` : `${ORIGIN}${op.path}`;
    return wrap(`[${label}](${href}) (\`${op.operationId}\`): ${op.summary}. ${op.description}`, "- ", "  ");
  });
  return [BEGIN, ...items, END].join("\n");
}

export function withEndpointBlock(llms: string): string {
  const start = llms.indexOf(BEGIN);
  const end = llms.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${LLMS_PATH}: the generated endpoint block's markers are missing`);
  return llms.slice(0, start) + endpointBlock() + llms.slice(end + END.length);
}

if (import.meta.main) {
  const current = readFileSync(LLMS_PATH, "utf8");
  const next = withEndpointBlock(current);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error(`${LLMS_PATH}: the endpoint block is stale; run bun tools/gen-llms-api.ts`);
      process.exit(1);
    }
    console.log(`${LLMS_PATH}: endpoint block current (${OPERATIONS.length} operations)`);
  } else {
    writeFileSync(LLMS_PATH, next);
    console.log(`${LLMS_PATH}: wrote ${OPERATIONS.length} operations`);
  }
}
