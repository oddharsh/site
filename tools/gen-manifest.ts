#!/usr/bin/env node
// gen-manifest.mjs — derive the mechanical, drift-prone projections of the site
// surface registry from site-manifest.json, so the places that used to list the
// site's pages by hand cannot fork again.

import { readFileSync, writeFileSync } from "node:fs";
import { PROFILES } from "../tools/photos/shell-data.ts";

export const MANIFEST = "config/site-manifest.json";
const NAV = "src/client/nav-run.js";
const WORKER_MOD = "src/worker/lib/site-manifest.ts";
const FENCE_SECTIONS = [["garage", "garage-pages"], ["lwe", "lwe-pages"]];

export function readManifest() {
  return JSON.parse(readFileSync(MANIFEST, "utf8"));
}

const seg = (p) => p.split("/").pop();
const paletteLabel = (s) => `${s.section} · ${s.short || seg(s.path)}`;
const navEntry = (s) =>
  `    { label: ${JSON.stringify(paletteLabel(s))}, path: ${JSON.stringify(s.path)}, hint: ${JSON.stringify(s.hint)} },`;

export function navFenceBody(surfaces, section) {
  return surfaces
    .filter((s) => s.section === section && s.kind === "content" && s.flags.run)
    .map(navEntry)
    .join("\n");
}

export function runProfilesBody(profiles = PROFILES) {
  return profiles.map((profile) => {
    const fields = ["label", "icon", "hint", "url"]
      .filter((key) => profile[key])
      .map((key) => `${key}: ${JSON.stringify(profile[key])}`)
      .join(", ");
    return `    { ${fields} },`;
  }).join("\n").replace(/,$/, "");
}

export function agentSurfaces(surfaces) {
  return surfaces
    .filter((s) => s.flags.agents)
    .map((s) => ({ path: s.path, title: s.title, mimeType: s.mimeType ?? "text/html", description: s.description }));
}

export function webmentionPaths(surfaces) {
  return surfaces.filter((s) => s.flags.webmention).map((s) => s.path);
}
export function webmentionSections(surfaces) {
  return surfaces.filter((s) => s.flags.webmention && s.kind === "section").map((s) => s.path);
}

export function workerModule(surfaces) {
  return `// lib/site-manifest.js — the worker-facing projections of the site surface
// registry, GENERATED by tools/gen-manifest.ts from site-manifest.json
// (do not hand-edit; edit the registry and re-run the generator). AGENT_SURFACES
// is the catalog MCP resources/list serves: every surface flagged agents:true,
// trimmed to what a client needs to decide where to look. WEBMENTION_* are the
// pages that accept an inbound webmention. build.ts #8 fails the deploy if any
// of these drift from the registry.
export const AGENT_SURFACES = ${JSON.stringify(agentSurfaces(surfaces), null, 2)};

// Paths that accept a webmention, and the subset that are section indexes whose
// leaf content (writing posts) is vouched for too.
export const WEBMENTION_PATHS = ${JSON.stringify(webmentionPaths(surfaces), null, 2)};
export const WEBMENTION_SECTIONS = ${JSON.stringify(webmentionSections(surfaces), null, 2)};
`;
}

export function readFenceBody(src, marker) {
  const start = src.indexOf(`generated:${marker}:start`);
  const end = src.indexOf(`generated:${marker}:end`);
  if (start === -1 || end === -1) throw new Error(`missing generated:${marker} fence`);
  const afterStart = src.indexOf("\n", start) + 1;
  const endLineStart = src.lastIndexOf("\n", end) + 1;
  return src.slice(afterStart, endLineStart).replace(/\n$/, "");
}

function writeFenceBody(src, marker, body) {
  const start = src.indexOf(`generated:${marker}:start`);
  const end = src.indexOf(`generated:${marker}:end`);
  if (start === -1 || end === -1) throw new Error(`missing generated:${marker} fence`);
  const afterStart = src.indexOf("\n", start) + 1;
  const endLineStart = src.lastIndexOf("\n", end) + 1;
  return src.slice(0, afterStart) + body + "\n" + src.slice(endLineStart);
}

function main() {
  const { surfaces } = readManifest();

  let nav = readFileSync(NAV, "utf8");
  let counts = [];
  for (const [section, marker] of FENCE_SECTIONS) {
    const body = navFenceBody(surfaces, section);
    nav = writeFenceBody(nav, marker, body);
    counts.push(`${body.split("\n").filter(Boolean).length} ${section}`);
  }
  nav = writeFenceBody(nav, "run-profiles", runProfilesBody());
  writeFileSync(NAV, nav);
  console.log(`nav-run.js: ${counts.join(" + ")} palette entries + ${PROFILES.length} profiles`);

  writeFileSync(WORKER_MOD, workerModule(surfaces));
  console.log(`lib/site-manifest.js: ${agentSurfaces(surfaces).length} agent surfaces`);
}

if (import.meta.main) main();
