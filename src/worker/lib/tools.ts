// Component schemas from lib/openapi.ts that a tool returns without a REST
// operation of its own: the Lens summaries (lensObservationSummary) and an
// archive photo's metadata (photo_recipe in mcp.ts), and lens_compare's result,
// which is /lens/compare.json's body without its ok and comparedAt wrapper.
// tools/gen-tool-schemas.ts inlines each into tool-schemas.json by name.
export const TOOL_COMPONENTS = ["LensSummary", "LensComparisonValue", "PhotoMetadata"];

// Undefined until the generator has written the key, which it can only do after
// importing this file. contract-mcp-tools-share-their-rest-schemas fails on the
// stale JSON, and contract-mcp-schemas-are-complete on the open schema.
export function sharedSchema(key: string) {
  return (TOOL_SCHEMAS as { components?: Record<string, Record<string, unknown>> }).components?.[key];
}

// A tool that runs the same function as a REST operation (operationId) takes
// that operation's schemas rather than restating them: its outputSchema is the
// operation's 200 body, and a parameter with no description of its own takes
// the operation's description of the parameter with the same name. The Lens
// tools return a summary of their own rather than the REST body, so they name
// their operation in parametersFrom and take only its parameter descriptions.
// Both come from tool-schemas.json, which contract-mcp-tools-share-their-rest-
// schemas holds equal to the generator's output and checks against each mapped
// tool's real result.
export const TOOL_OPERATIONS = DATA_TOOL_DEFINITIONS.flatMap((tool) =>
  tool.operationId ? [{ operationId: tool.operationId, output: true }] : tool.parametersFrom ? [{ operationId: tool.parametersFrom, output: false }] : [],
);

function withOperationSchemas(tool) {
  const operationId = tool.operationId ?? tool.parametersFrom;
  if (tool.outputFrom) {
    const { outputFrom, ...rest } = tool;
    return withOperationSchemas({ ...rest, outputSchema: sharedSchema(outputFrom) });
  }
  if (!operationId) return tool;
  const described: Record<string, string> = TOOL_SCHEMAS.parameters[operationId] ?? {};
  const properties = Object.fromEntries(
    Object.entries(tool.inputSchema.properties ?? {}).map(([name, prop]: [string, Record<string, unknown>]) => [
      name,
      prop.description || !described[name] ? prop : { ...prop, description: described[name] },
    ]),
  );
  const { operationId: _operationId, parametersFrom: _parametersFrom, ...rest } = tool;
  const inputSchema = { ...tool.inputSchema, properties };
  const outputSchema = tool.operationId ? TOOL_SCHEMAS.outputs[tool.operationId] : tool.outputSchema;
  return outputSchema ? { ...rest, inputSchema, outputSchema } : { ...rest, inputSchema };
}

export const DATA_TOOLS = DATA_TOOL_DEFINITIONS.map((tool) => mcpTool(withOperationSchemas(tool)));

export const DATA_TOOL_NAMES = new Set(DATA_TOOLS.map((t) => t.name));

// The result is Record<string, any> for the same reason mcp.ts's callTool is: one
// function dispatches every DATA_TOOLS entry, each returns its own payload
// shape, and the sentinel fields (_error among them) ride alongside. Inference
// picks one arm of that union and every caller reading another arm's field looks
// like a typo.
export async function callDataTool(name, args, request, env, ctx): Promise<Record<string, unknown>> {
  args = asRecord(args) || {};
  if (name === "ask") {
    // Validated through the ROUTE's parser, with a synthetic URL standing in for
    // the query string. Site tokens, mode refusals, `prev` handling and the
    // query_id default are one implementation, so the two doors cannot disagree
    // about what a request means — which is the whole reason the protocol
    // specifies them together.
    const parsed = parseAskRequest(new URL("https://aadhar.sh/ask"), args);
    if (!parsed.ok) return toolError(parsed.error.message);
    return nlwebAsk(env, parsed.params, request);
  }
  if (name === "search_site") return searchSite(env, args.q, args.limit);
  if (name === "photo_query") return queryPhotos(env, args, ctx);
  if (name === "coffee_availability") return getPublicAvailability(env, ctx);
  if (name === "change_radar") {
    try {
      return await readAroundChanges(env, args.limit);
    } catch {
      return toolError("change history is temporarily unavailable");
    }
  }
  if (name === "now_playing") {
    const pid = await currentPlaylistId(env);
    try {
      const tracks = await getTracksSWR(env, ctx, pid, { buildOnMiss: true });
      return tracks || { available: false, playlist_id: pid, tracks: [] };
    } catch {
      return toolError("the playlist is temporarily unavailable");
    }
  }
  if (name === "lens_inspect") {
    return lensToolResult(await LENS_INSPECT.run({ url: args.url, skipBotViews: true }, request, env, ctx), lensObservationSummary);
  }
  if (name === "lens_page") {
    return lensToolResult(await LENS_INSPECT.run({ url: args.url, phases: ["page"] }, request, env, ctx), lensObservationSummary);
  }
  if (name === "lens_compare") {
    return lensToolResult(await LENS_COMPARE.run({ left: args.left, right: args.right }, request, env, ctx));
  }
  if (name === "find_events") {
    try {
      return await serendipityFindEvents(env, args);
    } catch {
      return toolError("the event pool is temporarily unavailable");
    }
  }
  return { _unknown: true };
}
