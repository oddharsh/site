#!/usr/bin/env node
// gen-manifest.mjs — derive the mechanical, drift-prone projections of the site
// surface registry from site-manifest.json, so the places that used to list the
// site's pages by hand cannot fork again.
//
//   node scripts/gen-manifest.mjs        # regen the worker module + nav.js fences
//
// What this OWNS (regenerated between markers; do not hand-edit those regions):
//   - holding/_worker.js/lib/site-manifest.js  — AGENT_SURFACES, the projection
//     MCP resources/list serves (agents:true only, no shell bytes)
//   - holding/nav.js generated:garage-pages + generated:lwe-pages — the Run
//     palette's garage/lwe sub-entries (terse {label,path,hint}, no temporal data)
//
// What this deliberately does NOT own (hand-authored, VERIFIED by build.mjs #8):
//   - sitemap.xml — carries per-page hand-tuned <lastmod>; generating would
//     flatten a real SEO freshness signal. build.mjs enforces coverage instead.
//   - holding/garage/index.html — rich hand-written gallery cards. Verified.
//   - nav.js top-level PAGES (Home/photos/…) — hand-authored. Verified subset.
//
// The projection functions below are PURE and exported, so build.mjs re-runs the
// exact same logic in-memory and fails the deploy if a committed output drifts.
// Only main() touches the filesystem, and only when run directly.

import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const MANIFEST = "site-manifest.json";
const NAV = "holding/nav.js";
const WORKER_MOD = "holding/_worker.js/lib/site-manifest.js";
const FENCE_SECTIONS = [["garage", "garage-pages"], ["lwe", "lwe-pages"]];

export function readManifest() {
  return JSON.parse(readFileSync(MANIFEST, "utf8"));
}

// palette label: "<section> · <short|last-path-segment>" — a few surfaces carry a
// custom `short` the path can't spell (vigenère's accent, "programmable crypto").
const seg = (p) => p.split("/").pop();
const paletteLabel = (s) => `${s.section} · ${s.short || seg(s.path)}`;
const navEntry = (s) =>
  `    { label: ${JSON.stringify(paletteLabel(s))}, path: ${JSON.stringify(s.path)}, hint: ${JSON.stringify(s.hint)} },`;

// the Run-palette entries for one fenced section (garage / lwe), in registry order.
export function navFenceBody(surfaces, section) {
  return surfaces
    .filter((s) => s.section === section && s.kind === "content" && s.flags.run)
    .map(navEntry)
    .join("\n");
}

// the agent catalog: only agents:true surfaces, only the fields resources/list
// needs, so the worker bundle carries a purpose-built list rather than the registry.
export function agentSurfaces(surfaces) {
  return surfaces
    .filter((s) => s.flags.agents)
    .map((s) => ({ path: s.path, title: s.title, kind: s.kind, description: s.description }));
}

export function workerModule(surfaces) {
  return `// lib/site-manifest.js — the agent-facing projection of the site surface
// registry, GENERATED by scripts/gen-manifest.mjs from site-manifest.json
// (do not hand-edit; edit the registry and re-run the generator). This is the
// catalog MCP resources/list serves: every surface flagged agents:true, trimmed
// to what a client needs to decide where to look. build.mjs #8 fails the deploy
// if this drifts from the registry.
export const AGENT_SURFACES = ${JSON.stringify(agentSurfaces(surfaces), null, 2)};
`;
}

// read the current body strictly between a fence's start/end marker lines.
export function readFenceBody(src, marker) {
  const start = src.indexOf(`generated:${marker}:start`);
  const end = src.indexOf(`generated:${marker}:end`);
  if (start === -1 || end === -1) throw new Error(`missing generated:${marker} fence`);
  const afterStart = src.indexOf("\n", start) + 1;
  const endLineStart = src.lastIndexOf("\n", end) + 1;
  return src.slice(afterStart, endLineStart).replace(/\n$/, "");
}

function writeFenceBody(src, marker, body) {
  const start = src.indexOf(`generated:${marker}:start`);
  const end = src.indexOf(`generated:${marker}:end`);
  if (start === -1 || end === -1) throw new Error(`missing generated:${marker} fence`);
  const afterStart = src.indexOf("\n", start) + 1;
  const endLineStart = src.lastIndexOf("\n", end) + 1;
  return src.slice(0, afterStart) + body + "\n" + src.slice(endLineStart);
}

function main() {
  const { surfaces } = readManifest();

  let nav = readFileSync(NAV, "utf8");
  let counts = [];
  for (const [section, marker] of FENCE_SECTIONS) {
    const body = navFenceBody(surfaces, section);
    nav = writeFenceBody(nav, marker, body);
    counts.push(`${body.split("\n").filter(Boolean).length} ${section}`);
  }
  writeFileSync(NAV, nav);
  console.log(`nav.js: ${counts.join(" + ")} palette entries`);

  writeFileSync(WORKER_MOD, workerModule(surfaces));
  console.log(`lib/site-manifest.js: ${agentSurfaces(surfaces).length} agent surfaces`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
